"""Generate ``docs/checks.md`` and ``docs/report.schema.json`` from the code.

Nothing in these files is typed by hand: the check catalogue is rendered from the registry and the
JSON Schema from the pydantic report model. A test fails if the committed copies are stale.
"""

from __future__ import annotations

from pathlib import Path

from ngs_preflight import __version__
from ngs_preflight.models import SCHEMA_VERSION
from ngs_preflight.registry import CheckSpec, all_checks
from ngs_preflight.report.json_report import render_schema

GROUPS = [
    ("BED", "Target regions (BED)"),
    ("SS", "Sample sheet"),
    ("REF", "Reference compatibility"),
    ("ID", "Sample identity (optional, uses somalier)"),
]

REQUIRES_TEXT = {
    "reference": "a reference (`--reference`)",
    "reads_dir": "the read-file folder (`--reads-dir`)",
}


def _needs(spec: CheckSpec) -> str:
    if spec.id.startswith("ID"):
        return "`--identity`, somalier, `--sites`"
    return ", ".join(REQUIRES_TEXT[r] for r in spec.requires) or "-"


def anchor(check_id: str) -> str:
    return check_id.lower()


def render_checks_md() -> str:
    checks = all_checks()
    out: list[str] = []
    out.append("# Check catalogue")
    out.append("")
    out.append(
        "<!-- Generated by `preflight docs` from the check registry "
        f"(ngs-preflight {__version__}). "
        "Do not edit by hand; a test fails if this file is out of date. -->"
    )
    out.append("")
    out.append(
        f"This page lists every check in ngs-preflight {__version__}. It is generated from the "
        "same registry the tool runs, so it cannot drift from the code. Run "
        "`preflight explain <ID>` to see one entry in the terminal."
    )
    out.append("")
    out.append("## How to read this page")
    out.append("")
    out.append(
        "- **ERROR** means the submission is likely to fail or give wrong results. Fix it first."
    )
    out.append(
        "- **WARN** means something looks wrong or risky. Review it; "
        "with `--strict` it counts as an error."
    )
    out.append("- **INFO** is a note or summary. It never affects the exit code.")
    out.append(
        "- In the message text, anything in `{braces}` is filled in with values from your files "
        "when the check fires."
    )
    out.append(
        "- Exit codes of `preflight check`: `0` pass, `1` errors found (or warnings with "
        "`--strict`), `2` warnings only, `3` tool or usage error."
    )
    out.append("")
    out.append("## Summary")
    out.append("")
    out.append("| ID | Severity | What it checks | Needs |")
    out.append("|---|---|---|---|")
    for spec in checks:
        out.append(
            f"| [{spec.id}](#{anchor(spec.id)}) | {spec.severity.value} | {spec.title} | "
            f"{_needs(spec)} |"
        )
    for prefix, heading in GROUPS:
        group = [c for c in checks if c.group == prefix]
        if not group:
            continue
        out.append("")
        out.append(f"## {heading}")
        for spec in group:
            out.append("")
            out.append(f'<a id="{anchor(spec.id)}"></a>')
            out.append(f"### {spec.id}: {spec.title}")
            out.append("")
            out.append(f"**Severity:** {spec.severity.value}. **Needs:** {_needs(spec)}.")
            out.append("")
            out.append("**Message shown to the customer**")
            out.append("")
            out.append("> " + spec.message.replace("\n", " "))
            out.append("")
            out.append("**How it works**")
            out.append("")
            out.append(spec.detail)
            out.append("")
            out.append("**Suggested fix**")
            out.append("")
            out.append("> " + spec.fix.replace("\n", " "))
            if spec.notes:
                out.append("")
                out.append("**Notes**")
                out.append("")
                out.append(spec.notes)
    out.append("")
    out.append(f"*JSON report format version: {SCHEMA_VERSION}. See `docs/json-report.md`.*")
    out.append("")
    return "\n".join(out)


def generated_files() -> dict[str, str]:
    """Relative path (under docs/) -> expected content."""
    return {"checks.md": render_checks_md(), "report.schema.json": render_schema()}


def write_docs(out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, content in generated_files().items():
        path = out_dir / name
        path.write_text(content, encoding="utf-8", newline="\n")
        written.append(path)
    return written


def stale_docs(out_dir: Path) -> list[Path]:
    """Generated files in ``out_dir`` that are missing or differ from the registry."""
    stale = []
    for name, content in generated_files().items():
        path = out_dir / name
        if not path.exists() or path.read_text(encoding="utf-8").replace("\r\n", "\n") != content:
            stale.append(path)
    return stale
