"""Record what real somalier reports for the committed trio fixtures, and render the docs from it.

    python scripts/record_identity_observations.py           # run somalier, rewrite both files
    python scripts/record_identity_observations.py --check   # no somalier needed: is the doc stale?

somalier comes from --somalier-cmd, else $PREFLIGHT_SOMALIER_CMD, else ``somalier`` on PATH.
The numbers are never typed by hand: ``tests/data/identity/observed.json`` is written from
somalier's own output, and ``docs/identity-fixtures.md`` is rendered from that JSON.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from ngs_preflight.identity.somalier import SomalierRunner  # noqa: E402
from ngs_preflight.runner import Options, run_preflight  # noqa: E402

DATA = ROOT / "tests" / "data" / "identity"
OBSERVED = DATA / "observed.json"
DOC = ROOT / "docs" / "identity-fixtures.md"
SITES = 17_766
SITES_FILE = DATA / "sites.hg38.vcf.gz"
TRIO = ["HG002", "HG003", "HG004"]
ID_CHECKS = ["ID001", "ID002", "ID003", "ID004", "ID005"]

# name -> (what was engineered, sheet, extra files)
SCENARIOS = {
    "trio": ("nothing, the true family", "trio.csv", []),
    "duplicate": (
        "HG002 submitted a second time as HG002_copy",
        "trio_duplicate.csv",
        ["HG002_copy.somalier"],
    ),
    "swapped": (
        "HG002 (son) and HG003 (father) swapped in the pedigree",
        "trio_swapped.csv",
        [],
    ),
    "wrong_sex": ("HG002 declared female in the sheet", "trio_wrong_sex.csv", []),
}


def _scenario_hits(runner_cmd: str | None, sheet: str, files: list[str]) -> dict[str, int]:
    inputs = [str(DATA / f"{s}.somalier") for s in TRIO] + [str(DATA / f) for f in files]
    report = run_preflight(
        Options(
            samplesheet=str(DATA / sheet),
            identity=True,
            sites=str(SITES_FILE),
            somalier_cmd=runner_cmd,
            identity_inputs=inputs,
        )
    )
    counts: dict[str, int] = {}
    for finding in report.all_findings():
        if finding.check_id in ID_CHECKS:
            counts[finding.check_id] = counts.get(finding.check_id, 0) + 1
    if report.skipped and any(s.check_id in ID_CHECKS for s in report.skipped):
        raise SystemExit("identity checks were skipped: " + report.skipped[0].reason)
    return counts


def observe(cmd: str | None) -> dict[str, object]:
    runner = SomalierRunner(cmd)
    ok, version = runner.available()
    if not ok:
        raise SystemExit(f"somalier is not available: {version}")
    files = [DATA / f"{s}.somalier" for s in TRIO]
    with tempfile.TemporaryDirectory(prefix="preflight-obs-") as tmp:
        result = runner.relate(files, SITES_FILE, Path(tmp) / "relate")
    samples = {
        sid: {
            "inferred_sex": s.inferred_sex,
            "n_hom_ref": s.n_hom_ref,
            "n_het": s.n_het,
            "n_hom_alt": s.n_hom_alt,
            "n_unknown": s.n_unknown,
            "x_het": s.x_het,
            "x_hom_alt": s.x_hom_alt,
        }
        for sid, s in sorted(result.samples.items())
    }
    pairs = [
        {
            "a": p.sample_a,
            "b": p.sample_b,
            "relatedness": p.relatedness,
            "ibs0": p.ibs0,
            "ibs2": p.ibs2,
            "n": p.n,
        }
        for p in sorted(result.pairs, key=lambda p: (p.sample_a, p.sample_b))
    ]
    scenarios = {
        name: {"engineered": what, "findings": _scenario_hits(cmd, sheet, extra)}
        for name, (what, sheet, extra) in SCENARIOS.items()
    }
    return {
        "somalier_version": version,
        "sites": SITES,
        "samples": samples,
        "pairs": pairs,
        "scenarios": scenarios,
    }


def render(data: dict[str, object]) -> str:
    samples: dict[str, dict[str, object]] = data["samples"]  # type: ignore[assignment]
    pairs: list[dict[str, object]] = data["pairs"]  # type: ignore[assignment]
    scenarios: dict[str, dict[str, object]] = data["scenarios"]  # type: ignore[assignment]
    out = [
        "# Identity test fixtures",
        "",
        "<!-- Generated by scripts/record_identity_observations.py from "
        "tests/data/identity/observed.json (real somalier output). Do not edit by hand. -->",
        "",
        "The sample identity checks (ID001-ID005) are tested against real `.somalier` files for "
        "the Genome in a Bottle Ashkenazim trio. This trio comprises HG002 (son), HG003 "
        "(father), and HG004 (mother). The files are in `tests/data/identity/` (about 210 KB "
        f"each). The values below were reported by somalier {data['somalier_version']} for "
        "these files. They are generated, not entered by hand.",
        "",
        "## How the fixtures were made",
        "",
        "- The 17,766 common hg38 sites bundled with somalier are committed here as "
        "`sites.hg38.vcf.gz` (somalier is provided under the MIT licence).",
        "- For autosomes, the Genome in a Bottle v4.2.1 GRCh38 benchmark genotypes are used for "
        "each individual. A site absent from a benchmark VCF is treated as homozygous for the "
        "reference allele (hom-ref) in that individual, because the VCF lists variants only. "
        "Hom-ref calls outside the benchmark's confident regions are therefore an assumption.",
        "- For chrX and chrY, genotypes were called with `bcftools mpileup | bcftools call` from "
        "the public Illumina NovaSeq 35x BAMs (GRCh38, no-alt analysis set) at the 365 chrX and "
        "17 chrY sites. The benchmark VCFs do not include chrX, so these calls are what make sex "
        "checking possible.",
        "- The genotypes for each individual were processed as a single-sample VCF with "
        "`somalier extract`. The procedure is documented in `scripts/fixture_recipe/`.",
        "- Direct extraction from the BAMs was not used, because streaming a 46 GB BAM took hours "
        "per sample and used several GB of memory. Since the inputs come from VCF, the files "
        "contain genotypes only and no read depth. somalier therefore does not infer sex itself, "
        "and ngs-preflight instead uses the proportion of heterozygous chrX calls (see ID004).",
        "",
        "## What somalier reports",
        "",
        f"Relatedness over {SITES:,} sites (the permitted parent-child range for ID002 is "
        "0.35-0.65):",
        "",
        "| Pair | Relatedness | IBS0 | IBS2 | Sites compared |",
        "|---|---|---|---|---|",
    ]
    for p in pairs:
        out.append(
            f"| {p['a']} / {p['b']} | {p['relatedness']:.3f} | {p['ibs0']} | {p['ibs2']} | "
            f"{p['n']:,} |"
        )
    out += [
        "",
        "Per sample (sex is inferred by the tool from chrX heterozygosity. HG002 and HG003 are "
        "male, and HG004 is female):",
        "",
        "| Sample | Sex | Hom-ref | Het | Hom-alt | Unknown | chrX het | chrX hom-alt |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for sid, s in samples.items():
        out.append(
            f"| {sid} | {s['inferred_sex']} | {s['n_hom_ref']:,} | {s['n_het']:,} | "
            f"{s['n_hom_alt']:,} | {s['n_unknown']:,} | {s['x_het']} | {s['x_hom_alt']} |"
        )
    out += [
        "",
        "## Engineered failures",
        "",
        "For each row, the identity checks were run on the trio with 1 deliberate mistake. "
        "Findings are counts per check.",
        "",
        "| Scenario | Mistake | Findings |",
        "|---|---|---|",
    ]
    for name, sc in scenarios.items():
        findings: dict[str, int] = sc["findings"]  # type: ignore[assignment]
        text = ", ".join(f"{k} x{v}" for k, v in sorted(findings.items())) or "none"
        out.append(f"| `{name}` | {sc['engineered']} | {text} |")
    out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only verify the doc is up to date")
    parser.add_argument("--somalier-cmd", default=None)
    args = parser.parse_args()
    if args.check:
        data = json.loads(OBSERVED.read_text(encoding="utf-8"))
        if DOC.read_text(encoding="utf-8") != render(data):
            print("docs/identity-fixtures.md is stale; rerun without --check", file=sys.stderr)
            return 1
        return 0
    cmd = args.somalier_cmd or os.environ.get("PREFLIGHT_SOMALIER_CMD")
    data = observe(cmd)
    OBSERVED.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8", newline="\n")
    DOC.write_text(render(data), encoding="utf-8", newline="\n")
    print(f"wrote {OBSERVED} and {DOC}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
